/**
 * 构建 mujing-canvas：
 *  - lib/index.js   host 服务 + HTTP 接口（Node ESM，@deepseek-ai/* 外部化，运行时取宿主 dsh 的实例）
 *  - lib/tools.js   agent 工具（同上）
 *  - lib/client.js  浏览器插件，包装为 window.__ModuleLoader__.load({ id, factory(require) })
 * 用法：node build.mjs [--harness ../deepseek-harness]
 */

import { readdirSync, readFileSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const argv = process.argv.slice(2)
const hi = argv.indexOf('--harness')
const rawHarness = (hi >= 0 && argv[hi + 1]) || process.env.DSH_HARNESS_DIR
const harness = rawHarness ? resolve(process.cwd(), rawHarness) : resolve(root, '../../deepseek-harness')

function loadEsbuild() {
  try { return createRequire(import.meta.url)('esbuild') } catch { /* 回退到 harness 的 pnpm store */ }
  const store = join(harness, 'node_modules/.pnpm')
  const dir = readdirSync(store).filter(d => /^esbuild@\d/.test(d)).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))[0]
  if (!dir) throw new Error(`找不到 esbuild：请在 ${harness} 执行 pnpm install`)
  return createRequire(join(store, dir, 'node_modules/esbuild/package.json'))('esbuild')
}

const esbuild = loadEsbuild()
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
await mkdir(join(root, 'lib'), { recursive: true })

/* host / tools */
await esbuild.build({
  entryPoints: { index: join(root, 'src/host/index.ts'), tools: join(root, 'src/tools.ts') },
  outdir: join(root, 'lib'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  packages: 'external',
  sourcemap: true,
  logLevel: 'warning',
})

/* client：CSS 以类名前缀 mj- 局部化，并在首次加载时注入 <style> */
const cssPlugin = {
  name: 'mujing-css',
  setup(build) {
    build.onLoad({ filter: /\.css$/ }, args => {
      const text = readFileSync(args.path, 'utf8')
      const names = new Set([...text.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/\.([A-Za-z][\w-]*)/g)].map(m => m[1]))
      const map = Object.fromEntries([...names].map(n => [n, `mj-${n}`]))
      const scoped = text.replace(/\.([A-Za-z][\w-]*)(?=[\s,.:{\[)>+~])/g, (m, n) => (map[n] ? `.${map[n]}` : m))
      return {
        loader: 'js',
        contents: `
const css = ${JSON.stringify(scoped)};
if (typeof document !== 'undefined' && !document.getElementById('mujing-style')) {
  const el = document.createElement('style'); el.id = 'mujing-style'; el.textContent = css; document.head.appendChild(el);
} else if (typeof document !== 'undefined') { document.getElementById('mujing-style').textContent = css; }
export default ${JSON.stringify(map)};`,
      }
    })
  },
}

const client = await esbuild.build({
  entryPoints: [join(root, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  plugins: [cssPlugin],
  logLevel: 'warning',
})
const body = client.outputFiles[0].text
await writeFile(join(root, 'lib/client.js'), `/* ${pkg.name}@${pkg.version} client bundle — generated by build.mjs */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${body}
    })(module, module.exports, require);
    return module.exports.default;
  },
});
`)

console.log('mujing-canvas 构建完成 → lib/index.js, lib/tools.js, lib/client.js')
